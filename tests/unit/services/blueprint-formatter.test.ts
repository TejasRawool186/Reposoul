/**
 * Tests for BlueprintFormatter
 *
 * Tests verify that each output format contains the expected content
 * and is well-formed (valid JSON, non-empty Markdown/text).
 */

import { describe, it, expect, beforeEach } from 'vitest';
import { BlueprintGenerator } from '../../../src/services/blueprint-generator';
import { BlueprintFormatter } from '../../../src/services/blueprint-formatter';
import {
  makeAnalysis,
  highPotentialAnalysis,
  makeDependencyAnalysis,
} from '../../fixtures/github.fixtures';

/** Build a blueprint to format */
function makeBlueprint(withDeps = false) {
  const gen = new BlueprintGenerator();
  return gen.generate(
    makeAnalysis(),
    withDeps ? makeDependencyAnalysis() : undefined
  );
}

describe('BlueprintFormatter', () => {
  let formatter: BlueprintFormatter;

  beforeEach(() => {
    formatter = new BlueprintFormatter();
  });

  // ─── JSON format ──────────────────────────────────────────────────────────

  describe('format — json', () => {
    it('produces valid JSON', () => {
      const output = formatter.format(makeBlueprint(), 'json');
      expect(() => JSON.parse(output)).not.toThrow();
    });

    it('JSON contains the blueprint repository field', () => {
      const bp = makeBlueprint();
      const output = formatter.format(bp, 'json');
      const parsed = JSON.parse(output);
      expect(parsed.repository).toBe(bp.repository);
    });

    it('JSON contains all top-level blueprint fields', () => {
      const output = formatter.format(makeBlueprint(), 'json');
      const parsed = JSON.parse(output);
      expect(parsed).toHaveProperty('recommendation');
      expect(parsed).toHaveProperty('overallScore');
      expect(parsed).toHaveProperty('riskRegister');
      expect(parsed).toHaveProperty('actionItems');
      expect(parsed).toHaveProperty('effortEstimate');
    });

    it('JSON is indented (pretty-printed)', () => {
      const output = formatter.format(makeBlueprint(), 'json');
      expect(output).toContain('  '); // indentation present
    });

    it('JSON preserves all action items', () => {
      const bp = makeBlueprint();
      const parsed = JSON.parse(formatter.format(bp, 'json'));
      expect(parsed.actionItems.length).toBe(bp.actionItems.length);
    });
  });

  // ─── Markdown format ──────────────────────────────────────────────────────

  describe('format — markdown', () => {
    it('starts with an h1 heading containing the repository name', () => {
      const bp = makeBlueprint();
      const output = formatter.format(bp, 'markdown');
      expect(output.startsWith(`# Revival Blueprint: ${bp.repository}`)).toBe(true);
    });

    it('contains a Scores section', () => {
      const output = formatter.format(makeBlueprint(), 'markdown');
      expect(output).toContain('## Scores');
    });

    it('contains Effort Estimate section', () => {
      const output = formatter.format(makeBlueprint(), 'markdown');
      expect(output).toContain('## Effort Estimate');
    });

    it('contains Risk Register section when risks exist', () => {
      const bp = new BlueprintGenerator().generate(highPotentialAnalysis);
      const output = formatter.format(bp, 'markdown');
      if (bp.riskRegister.length > 0) {
        expect(output).toContain('## Risk Register');
      }
    });

    it('contains Action Items section', () => {
      const output = formatter.format(makeBlueprint(), 'markdown');
      expect(output).toContain('## Action Items');
    });

    it('contains the recommendation in uppercase', () => {
      const bp = makeBlueprint();
      const output = formatter.format(bp, 'markdown');
      expect(output).toContain(bp.recommendation.toUpperCase());
    });

    it('contains overall score', () => {
      const bp = makeBlueprint();
      const output = formatter.format(bp, 'markdown');
      expect(output).toContain(`${bp.overallScore}/100`);
    });

    it('contains Dependency Upgrades section when upgrades present', () => {
      const bp = makeBlueprint(true);
      const output = formatter.format(bp, 'markdown');
      if (bp.dependencyUpgrades.length > 0) {
        expect(output).toContain('## Dependency Upgrades');
      }
    });

    it('ends with the REPOSOUL footer', () => {
      const output = formatter.format(makeBlueprint(), 'markdown');
      expect(output).toContain('Generated by REPOSOUL');
    });

    it('is longer than 500 characters', () => {
      const output = formatter.format(makeBlueprint(), 'markdown');
      expect(output.length).toBeGreaterThan(500);
    });
  });

  // ─── Text format ─────────────────────────────────────────────────────────

  describe('format — text', () => {
    it('starts with a divider line', () => {
      const output = formatter.format(makeBlueprint(), 'text');
      expect(output.startsWith('─')).toBe(true);
    });

    it('contains REVIVAL BLUEPRINT header', () => {
      const output = formatter.format(makeBlueprint(), 'text');
      expect(output).toContain('REVIVAL BLUEPRINT:');
    });

    it('contains SCORES section', () => {
      const output = formatter.format(makeBlueprint(), 'text');
      expect(output).toContain('SCORES');
    });

    it('contains EFFORT ESTIMATE section', () => {
      const output = formatter.format(makeBlueprint(), 'text');
      expect(output).toContain('EFFORT ESTIMATE');
    });

    it('contains ACTION ITEMS section', () => {
      const output = formatter.format(makeBlueprint(), 'text');
      expect(output).toContain('ACTION ITEMS');
    });

    it('contains the recommendation in uppercase', () => {
      const bp = makeBlueprint();
      const output = formatter.format(bp, 'text');
      expect(output).toContain(bp.recommendation.toUpperCase());
    });

    it('does not contain Markdown heading syntax', () => {
      const output = formatter.format(makeBlueprint(), 'text');
      // No ## headings in plain text
      expect(output).not.toMatch(/^##/m);
    });
  });

  // ─── Report format ────────────────────────────────────────────────────────

  describe('report', () => {
    it('contains a Table of Contents section', () => {
      const bp = makeBlueprint();
      const output = formatter.report(bp);
      expect(output).toContain('## Table of Contents');
    });

    it('TOC contains Scores link', () => {
      const bp = makeBlueprint();
      const output = formatter.report(bp);
      expect(output).toContain('[Scores](#scores)');
    });

    it('report is longer than the plain markdown output', () => {
      const bp = makeBlueprint();
      const md = formatter.format(bp, 'markdown');
      const report = formatter.report(bp);
      expect(report.length).toBeGreaterThan(md.length);
    });

    it('still starts with the h1 heading', () => {
      const bp = makeBlueprint();
      const output = formatter.report(bp);
      expect(output.startsWith(`# Revival Blueprint: ${bp.repository}`)).toBe(true);
    });
  });

  // ─── format() dispatch ───────────────────────────────────────────────────

  describe('format dispatch', () => {
    it('json and markdown produce different outputs', () => {
      const bp = makeBlueprint();
      const json = formatter.format(bp, 'json');
      const md = formatter.format(bp, 'markdown');
      expect(json).not.toBe(md);
    });

    it('text output does not start with {', () => {
      const output = formatter.format(makeBlueprint(), 'text');
      expect(output.startsWith('{')).toBe(false);
    });

    it('json output starts with {', () => {
      const output = formatter.format(makeBlueprint(), 'json');
      expect(output.startsWith('{')).toBe(true);
    });
  });
});
